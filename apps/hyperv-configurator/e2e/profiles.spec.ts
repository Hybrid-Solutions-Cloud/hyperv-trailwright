import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import PizZip from 'pizzip'
import {vmmProfileFixture} from '../src/testing/vmmProfileFixture'

test('desired VMM profile configuration survives review and exports without deployment code',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  page.on('dialog',dialog=>dialog.accept())
  const {project}=vmmProfileFixture()
  await page.goto('./')
  await page.locator('input[type=file]').first().setInputFiles({name:'profile.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await expect(page.getByText('Opened Profile creation example.')).toBeVisible()
  await page.getByRole('button',{name:/Hosts and provisioning/}).click()
  await expect(page.getByLabel('VMM library VHD / VHDX ID (GUID) *',{exact:true})).toHaveValue('66666666-6666-6666-6666-666666666666')
  await page.getByLabel('Dynamic image conversion *',{exact:true}).selectOption('retain')
  await page.getByLabel('Physical NIC profile IDs (one GUID per line) *',{exact:true}).fill('invalid-id')
  await page.getByRole('button',{name:/Review and exports/}).click()
  await page.getByRole('button',{name:/List distinct physical NIC profile GUIDs/}).click()
  await expect(page.getByLabel('Physical NIC profile IDs (one GUID per line) *',{exact:true})).toBeFocused()
  await page.getByLabel('Physical NIC profile IDs (one GUID per line) *',{exact:true}).fill('88888888-8888-8888-8888-888888888888')
  await page.getByLabel('Profile state *',{exact:true}).selectOption('existing')
  await expect(page.getByLabel('Dynamic image conversion *',{exact:true})).toHaveCount(0)
  await page.getByLabel('Profile state *',{exact:true}).selectOption('create')
  await expect(page.getByLabel('Dynamic image conversion *',{exact:true})).toHaveValue('retain')
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download project',exact:true}).click()
  const saved=await readFile((await(await downloadEvent).path())!,'utf8')
  expect(JSON.parse(saved).schemaVersion).toBe(32)
  expect(JSON.parse(saved).design.profiles[0].values).toMatchObject({profileState:'create',profileRef:'',vhdConversion:'retain',timeZoneId:'0'})
  await page.locator('input[type=file]').first().setInputFiles({name:'reopened-profile.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await page.getByRole('button',{name:/Implementation handoff/}).click()
  const profilePanel=page.locator('section.panel').filter({has:page.getByRole('heading',{name:'VMM physical-profile creation',exact:true})})
  await expect(profilePanel).toContainText('1 desired profiles · design-handoff')
  await expect(profilePanel).toContainText('It includes no deployment scripts.')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('profile-mobile.png'),fullPage:true})
  await page.getByRole('button',{name:/Review and exports/}).click()
  const zipEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download design package (.zip)',exact:true}).click()
  const file=await zipEvent;await file.saveAs(info.outputPath('profile-design.zip'))
  const zip=new PizZip(await readFile((await file.path())!)), plan=JSON.parse(zip.file('handoffs/vmm-profiles/plan.json')!.asText())
  expect(plan).toMatchObject({status:'design-handoff',runtimeQualified:false,automationReady:false,targets:[{storage:{bypassVhdConversion:true},result:{physicalComputerProfileId:null,reviewed:false}}]})
  expect(zip.file('reports/vmm-profile-creation.md')!.asText()).toContain('88888888-8888-8888-8888-888888888888')
  expect(zip.file('handoffs/vmm-profiles/README.md')!.asText()).toContain('New-SCPhysicalComputerProfile')
  const manifest=JSON.parse(zip.file('manifest.json')!.asText())
  expect(manifest.packagePurpose).toBe('configuration-design')
  expect(Object.keys(zip.files).filter(p=>/\.(ps1|psm1|sh|tf)$/i.test(p)||p.startsWith('adapters/')||p.startsWith('execution/'))).toEqual([])
  for(const entry of manifest.files){const bytes=zip.file(entry.path)!.asUint8Array();expect(bytes.length,entry.path).toBe(entry.sizeBytes);expect(createHash('sha256').update(bytes).digest('hex'),entry.path).toBe(entry.sha256)}
  expect(errors).toEqual([])
})
