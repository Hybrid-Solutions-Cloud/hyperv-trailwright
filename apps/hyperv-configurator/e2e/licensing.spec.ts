import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import PizZip from 'pizzip'
import {licensingFixture} from '../src/testing/licensingFixture'

test('physical licensing retains failover quantities, quote review and entitlement credit in its package',async({page},info)=>{
  page.on('dialog',d=>d.accept());const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  const {project}=licensingFixture();await page.goto('./')
  await page.locator('input[type=file]').first().setInputFiles({name:'licenses.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await expect(page.getByText('Opened Licensing example.')).toBeVisible()
  await page.getByRole('button',{name:/Licensing and costs/}).click()
  const gap=page.getByRole('table',{name:'License purchase gaps'}).getByRole('row').filter({hasText:'Windows core coverage'})
  await expect(gap).toContainText('USD 160')
  const second=page.locator('details[data-record-id="assignment-b"]')
  if(await second.getAttribute('open')===null)await second.locator('summary').click()
  await second.getByLabel('Peak virtual OSEs on this host',{exact:true}).fill('6')
  await expect(gap).toContainText('USD 240')
  await page.getByLabel('Quote status *',{exact:true}).selectOption('review')
  await expect(gap).toContainText('Quote / basis review needed')
  await expect(page.getByText('Partial estimate; 1 items unresolved',{exact:false})).toBeVisible()
  await page.getByLabel('Quote status *',{exact:true}).selectOption('quoted')
  await page.getByLabel('Price per unit',{exact:true}).fill('15')
  await expect(gap).toContainText('USD 360')
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download project',exact:true}).click()
  const saved=await readFile((await(await downloadEvent).path())!,'utf8')
  expect(JSON.parse(saved)).toMatchObject({schemaVersion:32,design:{licenses:[{values:{owned:8,unitPrice:15,calculationModel:'physical'}}]}})
  expect(JSON.parse(saved).design.licenseAssignments[1].values.peakVirtualOSEs).toBe(6)
  await page.locator('input[type=file]').first().setInputFiles({name:'reopen-licenses.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await expect(gap).toContainText('USD 360')
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('licensing-mobile.png'),fullPage:true})
  await page.getByRole('button',{name:/Review and exports/}).click()
  const zipEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download design package (.zip)',exact:true}).click()
  const file=await zipEvent;await file.saveAs(info.outputPath('licensing-design.zip'))
  const zip=new PizZip(await readFile((await file.path())!)),plan=JSON.parse(zip.file('plans/licensing-assessment.json')!.asText())
  expect(plan.rows[0]).toMatchObject({coreLicenses:64,required:32,covered:8,purchaseUnits:24,estimatedCost:360})
  expect(plan.rows[0].details[1]).toMatchObject({targetId:'host-b',calculation:{sets:3,coreLicenses:48}})
  expect(zip.file('reports/licensing.md')!.asText()).toContain('| 64 | 32 | 8 | 24 | Two-core pack | USD 360 / perpetual |')
  const manifest=JSON.parse(zip.file('manifest.json')!.asText())
  for(const entry of manifest.files){const bytes=zip.file(entry.path)!.asUint8Array();expect(bytes.length,entry.path).toBe(entry.sizeBytes);expect(createHash('sha256').update(bytes).digest('hex'),entry.path).toBe(entry.sha256)}
  expect(errors).toEqual([])
})

test('per-VM licensing exposes expired eligibility and restores its reviewed customer minimum',async({page})=>{
  page.on('dialog',d=>d.accept());const {project}=licensingFixture('virtual');await page.goto('./')
  await page.locator('input[type=file]').first().setInputFiles({name:'vm-licenses.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await page.getByRole('button',{name:/Licensing and costs/}).click()
  const gap=page.getByRole('table',{name:'License purchase gaps'}).getByRole('row').filter({hasText:'Windows core coverage'})
  await expect(gap).toContainText('USD 80')
  await page.getByLabel('Subscription / SA expiry (YYYY-MM-DD)',{exact:true}).fill('2026-01-01')
  await expect(gap).toContainText('Review rights / quantity')
  await page.getByRole('button',{name:/Review and exports/}).click()
  await page.getByRole('button',{name:/Per-VM licensing needs an eligible subscription/}).click()
  await expect(page.getByLabel('Per-VM licensing eligibility *',{exact:true})).toBeFocused()
  await page.getByLabel('Per-VM licensing eligibility *',{exact:true}).selectOption('subscription')
  await page.getByLabel('Entitlement term *',{exact:true}).selectOption('subscription')
  await page.getByLabel('Subscription / SA expiry (YYYY-MM-DD)',{exact:true}).fill('2027-09-11')
  await expect(gap).toContainText('USD 80')
  await expect(page.getByRole('table',{name:'License assignment calculations'})).toContainText('Example customer')
})

test('commercial rights and activation remain separate through review, save and reopen',async({page})=>{
  page.on('dialog',d=>d.accept());const {project}=licensingFixture();await page.goto('./')
  await page.locator('input[type=file]').first().setInputFiles({name:'rights.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await page.getByRole('button',{name:/Licensing and costs/}).click()
  const gap=page.getByRole('table',{name:'License purchase gaps'})
  const reviews=page.getByRole('table',{name:'Rights and activation review'})
  await page.getByLabel('Activation prerequisites and responsible owner *',{exact:true}).fill('')
  await expect(gap).toContainText('USD 160');await expect(reviews).toContainText('Review needed')
  await page.getByLabel('Activation prerequisites and responsible owner *',{exact:true}).fill('EXAMPLE activation owner and KMS prerequisites')
  await page.getByLabel('Applicable product terms / entitlement evidence *',{exact:true}).fill('')
  await expect(gap).toContainText('Review rights / quantity');await expect(reviews).toContainText('Prerequisites recorded')
  await page.getByRole('button',{name:/Review and exports/}).click()
  await page.getByRole('button',{name:/Record applicable product terms \/ entitlement evidence/}).click()
  await expect(page.getByLabel('Applicable product terms / entitlement evidence *',{exact:true})).toBeFocused()
  await page.getByLabel('Applicable product terms / entitlement evidence *',{exact:true}).fill('EXAMPLE reviewed commercial terms')
  await expect(gap).toContainText('USD 160')
  const savedEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download project',exact:true}).click()
  const saved=await readFile((await(await savedEvent).path())!,'utf8')
  expect(JSON.parse(saved).design.licenses[0].values).toMatchObject({rightsEvidence:'EXAMPLE reviewed commercial terms',activationMethod:'kms',entitlementTerm:'sa'})
  await page.locator('input[type=file]').first().setInputFiles({name:'rights-reopen.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await expect(gap).toContainText('USD 160');await expect(reviews).toContainText('Recorded commercial review')
})
