import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import PizZip from 'pizzip'
import { storageFixture } from '../src/testing/storageFixture'

test('storage lifecycle and disk mappings survive editing, reopen and package export',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept())
  await page.goto('./')
  const {project,add,fixed}=storageFixture()
  add('workloads','workload-a',{name:'Mapped workload',provisionedGiB:200,storageGiB:50})
  add('storagePaths','path-a',{name:'VM disk directory',volume:fixed.id,path:'C:\\ClusterStorage\\Fixed\\VMs',purpose:'disks',lifecycle:'create'})
  add('storageAllocations','disk-a',{name:'Mapped OS disk',resource:'workload-a',directory:'path-a',diskKey:'os',sizeGiB:200,usedGiB:50,provisioning:'dynamic'})
  await page.locator('input[type=file]').first().setInputFiles({name:'placement.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await page.getByRole('button',{name:/Storage/}).click()
  const coverage=page.getByRole('table',{name:'Resource disk coverage',exact:true})
  await expect(coverage.getByRole('row').filter({hasText:'Mapped workload'})).toContainText('2002000')
  const allocation=page.locator('details.resource').filter({has:page.locator('summary').filter({hasText:'Mapped OS disk'})})
  if(await allocation.getAttribute('open')===null)await allocation.locator('summary').click()
  await expect(allocation.getByLabel('Workload / component / SDN resource')).toHaveValue('workload-a')
  await allocation.getByLabel('Allocated logical size (GiB)').fill('150')
  await expect(coverage.getByRole('row').filter({hasText:'Mapped workload'})).toContainText('20015050')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('placement-mobile.png'),fullPage:true})
  const saveEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download project',exact:true}).click()
  const saved=await readFile((await(await saveEvent).path())!,'utf8')
  expect(JSON.parse(saved)).toMatchObject({schemaVersion:32,design:{storageAllocations:[{values:{resource:'workload-a',sizeGiB:150}}]}})
  await page.locator('input[type=file]').first().setInputFiles({name:'reopen-placement.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await page.getByRole('button',{name:/Review and exports/}).click()
  const zipEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download design package (.zip)',exact:true}).click()
  const download=await zipEvent;await download.saveAs(info.outputPath('placement-design.zip'))
  const zip=new PizZip(await readFile((await download.path())!)),assessment=JSON.parse(zip.file('plans/storage-assessment.json')!.asText())
  expect(assessment.placement.resources[0]).toMatchObject({mappedGiB:150,unmappedGiB:50})
  expect(zip.file('reports/schedules/Disk coverage.csv')!.asText()).toContain('mappedGiB')
  expect(zip.file('reports/storage.md')!.asText()).toContain('| Mapped workload | 200 | 150 | 50 |')
  const manifest=JSON.parse(zip.file('manifest.json')!.asText())
  for(const entry of manifest.files){const bytes=zip.file(entry.path)!.asUint8Array();expect(bytes.length,entry.path).toBe(entry.sizeBytes);expect(createHash('sha256').update(bytes).digest('hex'),entry.path).toBe(entry.sha256)}
  expect(errors).toEqual([])
})

test('storage review recalculates fixed and thin allocations and exports the reviewed design',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept())
  await page.goto('./')
  const {project}=storageFixture()
  await page.locator('input[type=file]').first().setInputFiles({name:'storage.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await expect(page.getByText('Opened Storage example.')).toBeVisible()
  await page.getByRole('button',{name:/Storage/}).click()
  const review=page.getByRole('region',{name:'Storage capacity review'})
  const capacity=review.getByRole('table',{name:'Example S2D capacity',exact:true})
  await expect(capacity.getByRole('row').filter({hasText:'Committed logical demand'})).toContainText('3 TiB')
  await expect(capacity.getByRole('row').filter({hasText:'Capacity-drive inventory'})).toContainText('24 TiB')
  await expect(review).toContainText('2 volumes · 2 CSV paths · 1 fixed · 1 thin')
  const volume=page.locator('details.resource').filter({has:page.locator('summary').filter({hasText:'Thin CSV'})})
  await volume.locator('summary').click()
  await volume.getByRole('combobox',{name:/^Provisioning/}).selectOption('fixed')
  await expect(capacity.getByRole('row').filter({hasText:'Committed logical demand'})).toContainText('10 TiB')
  await expect(review).toContainText('fixed allocations plus expected thin consumption exceed usable capacity')
  await volume.getByRole('combobox',{name:/^Provisioning/}).selectOption('thin')
  await volume.getByLabel('Expected consumed size (GiB)',{exact:true}).fill('2048')
  await expect(capacity.getByRole('row').filter({hasText:'Committed logical demand'})).toContainText('4 TiB')
  await expect(capacity.getByRole('row').filter({hasText:'Estimated raw committed footprint'})).toContainText('12 TiB')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.screenshot({path:info.outputPath('storage-mobile.png'),fullPage:true})
  const saveEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download project',exact:true}).click()
  const saved=await readFile((await(await saveEvent).path())!,'utf8')
  expect(JSON.parse(saved).design.volumes.find((v:{id:string})=>v.id==='thin-a').values).toMatchObject({provisioning:'thin',usedGiB:2048,sizeGiB:8192})
  await page.locator('input[type=file]').first().setInputFiles({name:'reopen-storage.json',mimeType:'application/json',buffer:Buffer.from(saved)})
  await page.getByRole('button',{name:/Storage/}).click()
  await expect(capacity.getByRole('row').filter({hasText:'Committed logical demand'})).toContainText('4 TiB')
  await page.getByRole('button',{name:/Review and exports/}).click()
  const zipEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download design package (.zip)',exact:true}).click()
  const download=await zipEvent;await download.saveAs(info.outputPath('storage-design.zip'))
  const zip=new PizZip(await readFile((await download.path())!))
  const assessment=JSON.parse(zip.file('plans/storage-assessment.json')!.asText())
  expect(assessment).toMatchObject({automationReady:false,executionState:'not-executed'})
  expect(assessment.systems.find((s:{id:string})=>s.id==='s2d-a')).toMatchObject({committedTiB:4,rawCommittedTiB:12,repairReserveTiB:6,rawHeadroomTiB:6})
  expect(zip.file('reports/storage.md')!.asText()).toContain('Committed logical demand | 4 TiB')
  expect(zip.file('reports/schedules/Storage capacity.csv')!.asText()).toContain('EstimatedRawCommittedTiB')
  const manifest=JSON.parse(zip.file('manifest.json')!.asText())
  for(const entry of manifest.files){const bytes=zip.file(entry.path)!.asUint8Array();expect(bytes.length,entry.path).toBe(entry.sizeBytes);expect(createHash('sha256').update(bytes).digest('hex'),entry.path).toBe(entry.sha256)}
  expect(errors).toEqual([])
})
