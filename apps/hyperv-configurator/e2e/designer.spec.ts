  const {project,snapshot}=discoveryFixture(new Date(Date.now()-120000).toISOString())
  await page.locator('input[type=file]').first().setInputFiles({name:'mapping-project.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))})
  await page.getByRole('button',{name:/Operations/}).click()
  await page.getByLabel('Discovery snapshot file').setInputFiles({name:'first.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(snapshot))})
