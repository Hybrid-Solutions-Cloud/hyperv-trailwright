test('SDN example exports a complete design archive with PDF, workbook and paired diagrams', async ({ page }, info) => {
  await page.goto('./')
  page.on('dialog', dialog => dialog.accept())
  await page.getByLabel('Reference design').selectOption('8')
  await page.getByRole('button', { name: 'Load example', exact: true }).click()
  await page.getByRole('button', { name: /SDN design and setup/ }).click()
  await expect(page.getByLabel('Controller architecture')).toHaveValue('host-cluster-role')
  await page.screenshot({ path: info.outputPath('sdn-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: /Review and exports/ }).click()
  const downloaded = page.waitForEvent('download', { timeout: 60000 })
  await page.getByRole('button', { name: 'Download design package (.zip)', exact: true }).click()
  const file = await downloaded, zip = new PizZip(await readFile((await file.path())!))
  await file.saveAs(info.outputPath('hyperv-design.zip'))
  for (const path of ['project.json', 'manifest.json', 'reports/design.md', 'reports/design.pdf', 'reports/inventory.xlsx', 'environment/hardware.yml', 'environment/ome.yml', 'environment/sdn.yml', 'plans/stage-plan.json', 'diagrams/topology.drawio', 'diagrams/topology.png', 'validation/results.json']) expect(zip.file(path), path).not.toBeNull()
  expect(zip.file('reports/design.pdf')!.asText().slice(0, 4)).toBe('%PDF')
  expect(Array.from(zip.file('diagrams/topology.png')!.asUint8Array().slice(0, 8))).toEqual([137, 80, 78, 71, 13, 10, 26, 10])
  expect(zip.file('environment/sdn.yml')!.asText()).toContain('host-cluster-role')
  const manifest = JSON.parse(zip.file('manifest.json')!.asText())
  expect(manifest.executionState).toBe('not_executed_by_configurator')
  expect(JSON.parse(zip.file('plans/stage-plan.json')!.asText())).toMatchObject({ kind: 'hyperv-stage-plan', automationReady: false })
  expect(manifest.files.every((f: { sha256: string }) => /^[a-f0-9]{64}$/.test(f.sha256))).toBe(true)
})

