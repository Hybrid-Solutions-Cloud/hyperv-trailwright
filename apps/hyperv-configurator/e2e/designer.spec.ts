  await page.getByLabel('Discovery reviewer').fill('Example reviewer');await page.getByLabel('Discovery review reason').fill('Confirmed VM identity following host migration')
  await row.getByRole('button',{name:'Confirm latest identity mapping',exact:true}).click()
