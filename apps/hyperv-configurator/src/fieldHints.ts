/** The hint to show for a field: its own hint first, then a shared hint for its key. */
export function hintFor(field: Field): string | undefined {
  return field.hint ?? fieldHints[field.key]
}

/** Copies collection-specific hints onto collection fields without changing shared field objects. */
export function applyCollectionHints(collections: Collection[]) {
  for (const collection of collections) {
    const hints = collectionHints[collection.key]
    if (hints) collection.fields = collection.fields.map(field => field.hint || !hints[field.key] ? field : {...field, hint: hints[field.key]})
  }
}
